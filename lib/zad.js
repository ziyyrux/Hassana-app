const MAX_MESSAGE_LENGTH = 2000;
const MAX_HISTORY_ITEMS = 16;

function normalizeHistory(history) {
  if (!Array.isArray(history)) return [];
  const cleaned = [];
  for (const item of history) {
    if (!item || typeof item !== 'object') continue;
    const role = item.role === 'model' || item.role === 'assistant' ? 'model' : item.role === 'user' ? 'user' : null;
    const text = typeof item.text === 'string' ? item.text.trim() : '';
    if (!role || !text) continue;
    cleaned.push({ role, text: text.slice(0, MAX_MESSAGE_LENGTH * 2) });
  }
  return cleaned.slice(-MAX_HISTORY_ITEMS);
}

function validateChatRequest(body) {
  if (!body || typeof body !== 'object') {
    return { ok: false, status: 400, error: 'الطلب غير صالح.' };
  }
  const rawMessage = typeof body.message === 'string' ? body.message.trim() : '';
  if (!rawMessage) {
    return { ok: false, status: 400, error: 'يرجى كتابة سؤالك أولًا.' };
  }
  if (rawMessage.length > MAX_MESSAGE_LENGTH) {
    return {
      ok: false,
      status: 400,
      error: `الرسالة طويلة جدًا. الحد الأقصى هو ${MAX_MESSAGE_LENGTH} حرف.`,
    };
  }
  const history = normalizeHistory(body.history);
  return { ok: true, message: rawMessage, history };
}

function buildGeminiContents(history, message) {
  const contents = [];
  for (const turn of history) {
    contents.push({
      role: turn.role,
      parts: [{ text: turn.text }],
    });
  }
  contents.push({
    role: 'user',
    parts: [{ text: message }],
  });
  return contents;
}

function mapGeminiError(err) {
  const status = err && (err.status || err.statusCode || err.code);
  const raw = String((err && (err.message || err.toString())) || '');
  const lower = raw.toLowerCase();

  if (raw.includes('MISSING_API_KEY')) {
    return {
      status: 503,
      code: 'MISSING_API_KEY',
      error: 'مفتاح Gemini API غير مُعدّ حاليًا. يرجى إضافته في إعدادات الأسرار (Settings > Secrets).',
    };
  }
  if (status === 401 || status === 403 || raw.includes('PERMISSION_DENIED') || raw.includes('API_KEY_INVALID') || lower.includes('api key')) {
    return {
      status: 401,
      code: 'INVALID_API_KEY',
      error: 'تعذّر التحقق من مفتاح Gemini API. يرجى التأكد من المفتاح في إعدادات الأسرار (Settings > Secrets).',
    };
  }
  if (status === 429 || raw.includes('RESOURCE_EXHAUSTED')) {
    return {
      status: 429,
      code: 'RATE_LIMIT',
      error: 'تم تجاوز الحد المؤقت للطلبات. يرجى الانتظار قليلًا ثم المحاولة مرة أخرى.',
    };
  }
  if (status === 404 || raw.includes('NOT_FOUND')) {
    return {
      status: 502,
      code: 'MODEL_NOT_FOUND',
      error: 'النموذج المطلوب غير متاح حاليًا. يرجى المحاولة لاحقًا.',
    };
  }
  if (status === 503 || raw.includes('UNAVAILABLE') || lower.includes('overloaded')) {
    return {
      status: 503,
      code: 'SERVICE_UNAVAILABLE',
      error: 'الخدمة مشغولة مؤقتًا. يرجى المحاولة مرة أخرى بعد لحظات.',
    };
  }
  if (status === 400 || raw.includes('INVALID_ARGUMENT')) {
    return {
      status: 400,
      code: 'BAD_REQUEST',
      error: 'تعذّر معالجة صيغة الطلب. يرجى إعادة صياغة سؤالك والمحاولة مرة أخرى.',
    };
  }
  if (lower.includes('fetch failed') || lower.includes('etimedout') || lower.includes('econn') || lower.includes('network') || lower.includes('abort')) {
    return {
      status: 502,
      code: 'NETWORK_ERROR',
      error: 'تعذّر الوصول إلى خدمة الذكاء الاصطناعي. يرجى المحاولة مرة أخرى بعد قليل.',
    };
  }
  return {
    status: 502,
    code: 'UPSTREAM_ERROR',
    error: 'حدث خطأ أثناء الاتصال بمساعد زاد. يرجى المحاولة مرة أخرى بعد قليل.',
  };
}

